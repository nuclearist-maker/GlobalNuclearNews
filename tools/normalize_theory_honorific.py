def convert(text):
    text=text.replace('</strong>다.','</strong>입니다.')
    text=text.replace('</code>다.','</code>입니다.')
    text=text.replace('`다.','`입니다.')
    for old,new in MAP: text=text.replace(old,new)
    return text

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--first',type=int,required=True); ap.add_argument('--last',type=int,required=True); args=ap.parse_args()
    for p in sorted((ROOT/'posts/theory').glob('*.html')):
        if not p.name[:3].isdigit(): continue
        n=int(p.name[:3])
        if args.first<=n<=args.last:
            old=p.read_text(encoding='utf-8'); new=convert(old)
            if new!=old: p.write_text(new,encoding='utf-8'); print(p.name)

if __name__=='__main__': main()
